#!/usr/bin/env node
/**
 * Emits public/pricing/paddle-config.js and dist/pricing/paddle-config.js from
 * environment variables.
 *
 * Why this exists: the pricing page is a plain HTML file under public/, and Vite
 * copies public/** verbatim — it never substitutes import.meta.env into it. So the
 * one thing the page cannot hard-code (which Paddle account it talks to) is written
 * out here instead, from PADDLE_ENV + PADDLE_CLIENT_TOKEN.
 *
 * This script never guesses. If the environment is unset, or the token prefix
 * contradicts it, it exits non-zero and writes nothing — so a build can never
 * silently point the live site at the wrong Paddle account.
 *
 *   npm run paddle:config
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const VALID_ENVIRONMENTS = ["sandbox", "production"];
// Paddle prefixes client-side tokens by environment. A production build holding a
// test_ token (or vice versa) is the wrong-account bug this script exists to catch.
const REQUIRED_PREFIX = { sandbox: "test_", production: "live_" };

/** Minimal .env reader — avoids taking a dependency for four lines of parsing. */
function readDotEnv(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const raw of readFileSync(path, "utf8").split("\n")) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    const value = line.slice(eq + 1).trim();
    // Strip one layer of matching quotes, if present.
    out[key] = value.replace(/^(['"])(.*)\1$/, "$2");
  }
  return out;
}

const dotEnv = readDotEnv(join(ROOT, ".env"));

/**
 * process.env wins over .env, and wins even when explicitly blank — `PADDLE_ENV= npm
 * run paddle:config` must fail rather than quietly fall back to a committed .env.
 */
function read(key) {
  return Object.hasOwn(process.env, key) ? process.env[key] : dotEnv[key];
}

function fail(message) {
  console.error(`\n  ✗ paddle:config — ${message}\n`);
  console.error("  Set PADDLE_ENV and PADDLE_CLIENT_TOKEN in .env (see .env.example).");
  console.error("  Tokens: Paddle dashboard > Developer tools > Authentication.\n");
  process.exit(1);
}

const environment = read("PADDLE_ENV");
const token = read("PADDLE_CLIENT_TOKEN");

if (!environment) {
  fail("PADDLE_ENV is not set. It has no default — set it to 'sandbox' or 'production'.");
}
if (!VALID_ENVIRONMENTS.includes(environment)) {
  fail(`PADDLE_ENV is '${environment}'. It must be exactly 'sandbox' or 'production'.`);
}
if (!token) {
  fail("PADDLE_CLIENT_TOKEN is not set.");
}
if (token.includes("replace_me")) {
  fail("PADDLE_CLIENT_TOKEN is still the .env.example placeholder.");
}

// Checked before the prefix rule so the paste error gets a message that names it —
// an API key here would be published to every visitor.
if (/^pdl_[a-z]+_apikey_/.test(token)) {
  fail(
    "PADDLE_CLIENT_TOKEN looks like a server-side API key (pdl_…_apikey_…). " +
      "Only a client-side token belongs in the browser — this page has no server to keep a secret in."
  );
}

const prefix = REQUIRED_PREFIX[environment];
if (!token.startsWith(prefix)) {
  fail(
    `PADDLE_ENV is '${environment}' but PADDLE_CLIENT_TOKEN does not start with '${prefix}'. ` +
      "Refusing to build against a mismatched Paddle account."
  );
}

const contents = `// GENERATED by scripts/gen-paddle-config.mjs — do not edit by hand.
// Run \`npm run paddle:config\` to regenerate from .env.
//
// This is a Paddle *client-side* token. It is public by design: every visitor's
// browser receives it. The server-side API key must never appear here.
window.__PADDLE_CONFIG__ = ${JSON.stringify({ environment, token }, null, 2)};
`;

// public/ so the page works on the Vite dev server; dist/ because that is what
// `gh-pages -d dist` actually deploys.
const targets = [join(ROOT, "public", "pricing"), join(ROOT, "dist", "pricing")];

for (const dir of targets) {
  mkdirSync(dir, { recursive: true });
  const file = join(dir, "paddle-config.js");
  writeFileSync(file, contents);
  console.log(`  ✓ ${file.replace(`${ROOT}/`, "")}`);
}

console.log(`  environment: ${environment}  token: ${token.slice(0, 9)}…\n`);
